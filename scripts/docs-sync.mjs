#!/usr/bin/env node
// Builds the Mintlify content in docs-site/ from the single sources of truth:
//   docs/*.md, CONTRIBUTING.md, CHANGELOG.md  ->  docs-site/**/*.mdx (frontmatter added, links rewritten)
//   /openapi.json (the app's route)           ->  docs-site/api-reference/openapi.json
// It also checks that docs-site/agents/tools.mdx lists every MCP tool registered in src/app/api/mcp/route.ts.
// Usage: npm run docs:sync   (set POSY_OPENAPI_URL to read the spec from somewhere else)
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const out = path.join(root, 'docs-site');
const SITE = 'https://posy.page';
const GH = 'https://github.com/Himanshu-Sangshetti/posy';

const PAGES = [
  { src: 'docs/connect.md', dest: 'agents/connect.mdx', title: 'Connect an AI app', description: 'Let Claude, ChatGPT, Cursor, VS Code, Claude Code or Codex make and edit your Posy page.' },
  { src: 'docs/format.md', dest: 'agents/format.mdx', title: 'The page file', description: 'One small JSON file describes a whole Posy page. Any chat can write it.' },
  { src: 'docs/ai-agents.md', dest: 'agents/guide.mdx', title: 'Agent guide', description: 'Rules, tile types, REST examples and the CLI for agents that edit a Posy page.' },
  { src: 'docs/self-hosting.md', dest: 'self-host/guide.mdx', title: 'Self-hosting guide', description: 'Run Posy with Docker, Compose, Vercel plus Turso, or any Node host.' },
  { src: 'docs/telemetry.md', dest: 'self-host/telemetry.mdx', title: 'Telemetry', description: 'What a self-hosted Posy sends, and how to turn it off.' },
  { src: 'CONTRIBUTING.md', dest: 'contribute/guide.mdx', title: 'Contributing', description: 'Dev setup, where things live, how to add a look, and what to run before a pull request.' },
  { src: 'CHANGELOG.md', dest: 'changelog.mdx', title: 'Changelog', description: 'What changed in each Posy release.' },
];

// Where a link in a source file should point inside the docs site (or out to the app / GitHub).
const LINKS = [
  [/\]\(\/docs\/format\)/g, '](/agents/format)'],
  [/\]\(\/docs\/agents\)/g, '](/agents/connect)'],
  [/\]\(ai-agents\.md(#[^)]*)?\)/g, '](/agents/guide$1)'],
  [/\]\(https:\/\/github\.com\/Himanshu-Sangshetti\/posy\/blob\/main\/docs\/ai-agents\.md\)/g, '](/agents/guide)'],
  [/\]\(\/(new|schema\/[^)]*)\)/g, `](${SITE}/$1)`],
  [/\]\(telemetry\.md(#[^)]*)?\)/g, '](/self-host/telemetry$1)'],
  [/\]\((CODE_OF_CONDUCT|SECURITY)\.md\)/g, `](${GH}/blob/main/$1.md)`],
];

/** Escape what MDX would parse as JSX or expressions, but leave fenced code and `inline code` alone. */
function escapeMdx(md) {
  let fence = false;
  return md.split('\n').map(line => {
    if (/^\s*(```|~~~)/.test(line)) { fence = !fence; return line; }
    if (fence) return line;
    return line.split(/(`[^`]*`)/).map((part, i) => i % 2 ? part : part.replace(/\{/g, '\\{').replace(/\}/g, '\\}').replace(/<(?![a-zA-Z/!]|\/)/g, '&lt;')).join('');
  }).join('\n');
}

function convert(md, p) {
  let body = md.replace(/^\uFEFF/, '').replace(/^# .*\n+/, '');
  body = body.replace(/<!-- docs-site: skip -->[\s\S]*?<!-- \/docs-site: skip -->\n*/g, '');
  for (const [re, to] of LINKS) body = body.replace(re, to);
  body = escapeMdx(body);
  // Markers in docs/*.md are HTML comments, so the app's own docs pages hide them.
  const install = body.includes('<!-- docs-site: install-buttons -->');
  body = body.replace('<!-- docs-site: install-buttons -->', '<InstallButtons />');
  const imports = install ? `import { INSTALL_LINKS, INSTALL_COPIES, InstallButtons } from '/snippets/install.jsx';\n\n` : '';
  const fm = `---\ntitle: ${JSON.stringify(p.title)}\ndescription: ${JSON.stringify(p.description)}\n---\n\n${imports}{/* Generated by scripts/docs-sync.mjs from ${p.src}. Edit the source, then run npm run docs:sync. */}\n\n`;
  return fm + body.trimEnd() + '\n';
}

for (const p of PAGES) {
  const src = path.join(root, p.src);
  if (!fs.existsSync(src)) { console.warn(`skip ${p.src} (missing)`); continue; }
  const dest = path.join(out, p.dest);
  fs.mkdirSync(path.dirname(dest), { recursive: true });
  fs.writeFileSync(dest, convert(fs.readFileSync(src, 'utf8'), p));
  console.log(`${p.src} -> docs-site/${p.dest}`);
}

// OpenAPI: prefer the running dev server, fall back to production; keep the committed copy if both fail.
const specDest = path.join(out, 'api-reference/openapi.json');
const urls = [process.env.POSY_OPENAPI_URL, 'http://localhost:3200/openapi.json', `${SITE}/openapi.json`].filter(Boolean);
let spec;
for (const u of urls) {
  try { const r = await fetch(u, { signal: AbortSignal.timeout(5000) }); if (r.ok) { spec = await r.json(); console.log(`openapi.json <- ${u}`); break; } } catch { /* try next */ }
}
if (spec) {
  const origin = new URL(spec.servers?.[0]?.url ?? SITE).origin;
  spec = JSON.parse(JSON.stringify(spec).replaceAll(origin, SITE));
  spec.servers = [{ url: SITE, description: 'posy.page (or your own server)' }];
  // Mintlify cannot resolve remote $refs; inline a pointer to the schema instead.
  const walk = n => {
    if (Array.isArray(n)) return n.forEach(walk);
    if (n && typeof n === 'object') {
      if (typeof n.$ref === 'string' && /^https?:/.test(n.$ref)) { const ref = n.$ref; delete n.$ref; n.type = 'object'; n.description = `A full Posy page. JSON Schema: ${ref}`; }
      Object.values(n).forEach(walk);
    }
  };
  walk(spec);
  // Short titles (and operationIds) so Mintlify makes readable URLs; the long text moves to the description.
  const TITLES = { 'get /api/v1/page': 'Get your page', 'put /api/v1/page': 'Replace the draft', 'post /api/v1/claim': 'Claim a username', 'post /api/v1/page/import': 'Import a page file', 'post /api/v1/page/tiles': 'Add a tile', 'patch /api/v1/page/theme': 'Change the theme', 'post /api/v1/page/theme': 'Change the theme (POST)', 'post /api/v1/page/publish': 'Publish', 'get /api/v1/public/{username}': 'Read a published page', 'get /api/v1/username': 'Check a username' };
  for (const [route, ops] of Object.entries(spec.paths)) for (const [method, op] of Object.entries(ops)) {
    const t = TITLES[`${method} ${route}`];
    if (!t) { console.warn(`openapi: no short title for ${method} ${route}`); continue; }
    op.description = [op.summary, op.description].filter(Boolean).join('\n\n');
    op.summary = t;
    op.operationId = t.toLowerCase().replace(/[^a-z0-9]+/g, '-').replace(/^-|-$/g, '');
  }
  fs.mkdirSync(path.dirname(specDest), { recursive: true });
  fs.writeFileSync(specDest, JSON.stringify(spec, null, 2) + '\n');
} else console.warn('openapi.json: no source reachable, keeping the committed copy');

// Tool reference check.
const route = fs.readFileSync(path.join(root, 'src/app/api/mcp/route.ts'), 'utf8');
const tools = [...route.matchAll(/registerTool\('([a-z_]+)'/g)].map(m => m[1]);
const toolsPage = fs.existsSync(path.join(out, 'agents/tools.mdx')) ? fs.readFileSync(path.join(out, 'agents/tools.mdx'), 'utf8') : '';
const missing = tools.filter(t => !toolsPage.includes(`name="${t}"`));
if (missing.length) { console.error(`docs-site/agents/tools.mdx is missing MCP tools: ${missing.join(', ')}`); process.exitCode = 1; }
else console.log(`mcp tools: all ${tools.length} documented`);
